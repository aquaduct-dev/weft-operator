#!/usr/bin/env bash
# gen_k3s_test.sh — emit the sh_test wrapper for a firecracker_k3s_test.
#
# Differs from gen_test.sh in that there are no expect_markers — pass/
# fail is decided by parsing the report JSON the guest test binary
# wrote between ===REPORT_BEGIN===/===REPORT_END===.
#
# The generated test script:
#   1. Launches the microvm runner (with FC_TIMEOUT as the hard cap).
#   2. Streams the serial log to stderr live (so Bazel callers see it).
#   3. After the VM exits, slices out the report-JSON payload between
#      the two markers and writes it to $SCENARIO_REPORT_PATH (if set)
#      AND to a stable in-test-undeclared-outputs path.
#   4. Returns 0 iff at least one pass_condition exists AND all of them
#      have passed=true. Otherwise prints the failing PCs to stderr and
#      returns non-zero.
#
# Args:
#   --out PATH               Output sh_test script.
#   --runner-rloc STR        rlocation path of the microvm runner.
#   --timeout N              Hard cap (seconds).
set -euo pipefail

OUT=""
RUNNER=""
TIMEOUT=""

while [ $# -gt 0 ]; do
  case "$1" in
    --out)         OUT="$2";     shift 2 ;;
    --runner-rloc) RUNNER="$2";  shift 2 ;;
    --timeout)     TIMEOUT="$2"; shift 2 ;;
    *) echo "gen_k3s_test: unknown arg: $1" >&2; exit 2 ;;
  esac
done

[ -n "$OUT" ]     || { echo "gen_k3s_test: --out required" >&2; exit 2; }
[ -n "$RUNNER" ]  || { echo "gen_k3s_test: --runner-rloc required" >&2; exit 2; }
[ -n "$TIMEOUT" ] || { echo "gen_k3s_test: --timeout required" >&2; exit 2; }

{
  cat <<'HEAD'
#!/usr/bin/env bash
# Generated by //tools/firecracker:gen_k3s_test — do not edit.
set -uo pipefail

if [[ -z "${RUNFILES_DIR:-}" ]]; then
  if [[ -d "${BASH_SOURCE[0]}.runfiles" ]]; then
    RUNFILES_DIR="${BASH_SOURCE[0]}.runfiles"
  elif [[ -d "$0.runfiles" ]]; then
    RUNFILES_DIR="$0.runfiles"
  fi
fi
if [[ -z "${RUNFILES_DIR:-}" && -n "${TEST_SRCDIR:-}" ]]; then
  RUNFILES_DIR="$TEST_SRCDIR"
fi
export RUNFILES_DIR
# shellcheck disable=SC1091
source "$RUNFILES_DIR/bazel_tools/tools/bash/runfiles/runfiles.bash"
HEAD
  printf 'RUNNER="$(rlocation %q)"\n' "$RUNNER"
  printf 'TIMEOUT=%s\n' "$TIMEOUT"
  cat <<'TAIL'

[[ -n "$RUNNER" && -x "$RUNNER" ]] || { echo "fc-k3s-test: runner not found or not executable" >&2; exit 1; }
command -v setsid >/dev/null || { echo "fc-k3s-test: setsid required (util-linux)" >&2; exit 1; }

LOG="$(mktemp -t fc-k3s-test.XXXXXX.log)"
TEST_OUTPUTS_DIR="${TEST_UNDECLARED_OUTPUTS_DIR:-$(mktemp -d -t fc-k3s-outputs.XXXXXX)}"
mkdir -p "$TEST_OUTPUTS_DIR"
cp_log="$TEST_OUTPUTS_DIR/serial.log"
# Always materialize the report inside TEST_UNDECLARED_OUTPUTS_DIR (bazel
# zips that into bazel-testlogs/.../test.outputs/outputs.zip and persists
# it across runs). If SCENARIO_REPORT_PATH is also set we'll best-effort
# copy the finished report there too — but the sandbox usually can't
# write to caller-provided host paths, so the persistent location is the
# source of truth and SCENARIO_REPORT_PATH is just a convenience.
report_dst="$TEST_OUTPUTS_DIR/report.json"

trap 'cp -f "$LOG" "$cp_log" 2>/dev/null || true; rm -f "$LOG"' EXIT

: >"$LOG"
tail -n +1 -F "$LOG" >&2 &
TAIL_PID=$!

echo "fc-k3s-test: launching microvm (cap ${TIMEOUT}s)" >&2
FC_TIMEOUT="$TIMEOUT" setsid -w "$RUNNER" >>"$LOG" 2>&1 &
RUNNER_PID=$!

deadline=$(( SECONDS + TIMEOUT + 10 ))
saw_poweroff=0
while :; do
  if ! kill -0 "$RUNNER_PID" 2>/dev/null; then
    break
  fi
  if grep -qF "K3S_POWEROFF" "$LOG" 2>/dev/null; then
    if [ "$saw_poweroff" -eq 0 ]; then
      saw_poweroff=1
      grace_deadline=$(( SECONDS + 8 ))
    fi
    if [ "$SECONDS" -ge "$grace_deadline" ]; then
      kill -TERM -- "-$RUNNER_PID" 2>/dev/null || true
      sleep 0.5
      kill -KILL -- "-$RUNNER_PID" 2>/dev/null || true
      break
    fi
  fi
  if [ "$SECONDS" -ge "$deadline" ]; then
    echo "fc-k3s-test: hard deadline hit; killing microvm" >&2
    kill -KILL -- "-$RUNNER_PID" 2>/dev/null || true
    break
  fi
  sleep 0.5
done
wait "$RUNNER_PID" 2>/dev/null || true
sleep 0.2
kill "$TAIL_PID" 2>/dev/null || true
wait "$TAIL_PID" 2>/dev/null || true

# Extract the report JSON between the markers, then trim anything before
# the first '{' line — even with k3s logs muted, an occasional kernel
# message or async writer can sneak into the marker block.
awk '
  /===REPORT_BEGIN===/ { capturing=1; next }
  /===REPORT_END===/   { capturing=0; next }
  capturing            { print }
' "$LOG" > "$report_dst.raw" || true

# Strip CR/LF noise.
sed -i 's/\r$//' "$report_dst.raw" 2>/dev/null || true
# Drop everything before the first line whose first non-space char is '{'.
sed -i -n '/^[[:space:]]*{/,$p' "$report_dst.raw" 2>/dev/null || true

if [ ! -s "$report_dst.raw" ]; then
  echo "fc-k3s-test: no report JSON found between markers (vm log copy at $cp_log)" >&2
  exit 1
fi

# Try to parse: if jq is available, validate + format. Otherwise pass
# through as-is. Tests in CI always have jq via the runner image.
if command -v jq >/dev/null && jq empty "$report_dst.raw" >/dev/null 2>&1; then
  jq . "$report_dst.raw" > "$report_dst"
else
  cp "$report_dst.raw" "$report_dst"
fi

# Best-effort mirror to the caller's path (eval.sh-style invocation).
# Sandboxed tests can't write to arbitrary host paths so this is allowed
# to fail silently — the persistent copy at $TEST_OUTPUTS_DIR/report.json
# (bazel-testlogs/.../test.outputs/outputs.zip!report.json) is the source
# of truth.
if [ -n "${SCENARIO_REPORT_PATH:-}" ] && [ "$SCENARIO_REPORT_PATH" != "$report_dst" ]; then
  if mkdir -p "$(dirname "$SCENARIO_REPORT_PATH")" 2>/dev/null && \
     cp "$report_dst" "$SCENARIO_REPORT_PATH" 2>/dev/null; then
    echo "fc-k3s-test: mirrored report to $SCENARIO_REPORT_PATH" >&2
  else
    echo "fc-k3s-test: SCENARIO_REPORT_PATH=$SCENARIO_REPORT_PATH unwritable from sandbox; persistent copy at outputs.zip!report.json" >&2
  fi
fi

if ! command -v jq >/dev/null; then
  echo "fc-k3s-test: jq missing; assuming report is valid" >&2
  exit 0
fi

if ! jq -e '.pass_conditions | type == "array" and length > 0' "$report_dst" >/dev/null; then
  echo "fc-k3s-test: report has no pass_conditions array" >&2
  cat "$report_dst" >&2
  exit 1
fi

failing=$(jq -r '.pass_conditions[] | select(.passed != true) | "\(.id)\t\(.label)\t\(.error // "")"' "$report_dst")
if [ -n "$failing" ]; then
  echo "fc-k3s-test: failing PCs:" >&2
  printf '%s\n' "$failing" >&2
  exit 1
fi

echo "fc-k3s-test: all pass_conditions passed" >&2
echo "fc-k3s-test: report at $report_dst" >&2
TAIL
} > "$OUT"
chmod +x "$OUT"
