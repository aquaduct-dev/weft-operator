#!/usr/bin/env bash
# gen_test.sh — emit a self-contained sh_test script that runs a
# firecracker_microvm with a timeout, captures serial output, and asserts
# expected/unexpected markers via fixed-string grep.
#
# The generated script kills the microVM as soon as every --expect marker
# has appeared in the log (early exit), which drops typical smoke-test
# wall-time from `timeout_seconds` to a few seconds. The hard timeout is
# still honored as the upper bound when markers never arrive. Unexpected
# markers are checked after the VM exits — if early exit fires before an
# unexpect marker would have been printed, that's a real signal, since
# the test would be falsely passing anyway.
#
# Args:
#   --out PATH               Output script path.
#   --runner-rloc STR        Rlocation path of the microvm runner sh_binary.
#   --timeout N              Boot timeout in seconds (hard cap).
# Repeatable:
#   --expect MARKER          Marker that must appear in the boot log.
#   --unexpect MARKER        Marker that must NOT appear in the boot log.

set -euo pipefail

OUT=""
RUNNER=""
TIMEOUT=""
EXPECT=()
UNEXPECT=()

while [ $# -gt 0 ]; do
  case "$1" in
    --out)         OUT="$2";     shift 2 ;;
    --runner-rloc) RUNNER="$2";  shift 2 ;;
    --timeout)     TIMEOUT="$2"; shift 2 ;;
    --expect)      EXPECT+=("$2"); shift 2 ;;
    --unexpect)    UNEXPECT+=("$2"); shift 2 ;;
    *) echo "gen_test: unknown arg: $1" >&2; exit 2 ;;
  esac
done

[ -n "$OUT" ]     || { echo "gen_test: --out required" >&2; exit 2; }
[ -n "$RUNNER" ]  || { echo "gen_test: --runner-rloc required" >&2; exit 2; }
[ -n "$TIMEOUT" ] || { echo "gen_test: --timeout required" >&2; exit 2; }

{
  cat <<'HEAD'
#!/usr/bin/env bash
# Generated by //tools/firecracker:gen_test — do not edit.
set -uo pipefail

if [[ -z "${RUNFILES_DIR:-}" ]]; then
  if [[ -d "${BASH_SOURCE[0]}.runfiles" ]]; then
    RUNFILES_DIR="${BASH_SOURCE[0]}.runfiles"
  elif [[ -d "$0.runfiles" ]]; then
    RUNFILES_DIR="$0.runfiles"
  fi
fi
if [[ -z "${RUNFILES_DIR:-}" && -n "${TEST_SRCDIR:-}" ]]; then
  RUNFILES_DIR="$TEST_SRCDIR"
fi
export RUNFILES_DIR
# shellcheck disable=SC1091
source "$RUNFILES_DIR/bazel_tools/tools/bash/runfiles/runfiles.bash"
HEAD
  printf 'RUNNER="$(rlocation %q)"\n' "$RUNNER"
  printf 'TIMEOUT=%s\n' "$TIMEOUT"
  printf 'EXPECT=(\n'
  for m in "${EXPECT[@]:-}"; do
    [ -z "$m" ] && continue
    printf '  %q\n' "$m"
  done
  printf ')\nUNEXPECT=(\n'
  for m in "${UNEXPECT[@]:-}"; do
    [ -z "$m" ] && continue
    printf '  %q\n' "$m"
  done
  printf ')\n'
  cat <<'TAIL'

[[ -n "$RUNNER" && -x "$RUNNER" ]] || { echo "fc-test: runner not found or not executable" >&2; exit 1; }
command -v setsid >/dev/null || { echo "fc-test: setsid required (util-linux)" >&2; exit 1; }

LOG="$(mktemp -t fc-test.XXXXXX.log)"
trap 'rm -f "$LOG"' EXIT
: >"$LOG"

# Stream the log to stderr as it arrives so callers see live boot output.
tail -n +1 -F "$LOG" >&2 &
TAIL_PID=$!

# setsid puts the runner in its own session/pgrp so we can kill the
# whole firecracker process tree with one `kill -- -PGID`. FC_TIMEOUT
# still propagates as a safety net — gen_test prefers to be the one to
# kill, but if the watcher loop crashes, runner's `timeout` finishes the
# job.
echo "fc-test: launching microvm (cap ${TIMEOUT}s, early-exit on markers)" >&2
FC_TIMEOUT="$TIMEOUT" setsid -w "$RUNNER" >>"$LOG" 2>&1 &
RUNNER_PID=$!

deadline=$(( SECONDS + TIMEOUT + 5 ))
killed_early=0
while :; do
  if ! kill -0 "$RUNNER_PID" 2>/dev/null; then
    break
  fi
  if [ "${#EXPECT[@]}" -gt 0 ]; then
    all_seen=1
    for m in "${EXPECT[@]}"; do
      [ -z "$m" ] && continue
      if ! grep -qF -- "$m" "$LOG" 2>/dev/null; then
        all_seen=0
        break
      fi
    done
    if [ "$all_seen" -eq 1 ]; then
      echo "fc-test: all expect markers seen; killing microvm early" >&2
      kill -TERM -- "-$RUNNER_PID" 2>/dev/null || true
      # Give the VM a moment to flush serial output before SIGKILL.
      for _ in 1 2 3 4 5; do
        kill -0 "$RUNNER_PID" 2>/dev/null || break
        sleep 0.2
      done
      kill -KILL -- "-$RUNNER_PID" 2>/dev/null || true
      killed_early=1
      break
    fi
  fi
  if [ "$SECONDS" -ge "$deadline" ]; then
    echo "fc-test: hard deadline hit; killing microvm" >&2
    kill -KILL -- "-$RUNNER_PID" 2>/dev/null || true
    break
  fi
  sleep 0.3
done
wait "$RUNNER_PID" 2>/dev/null || true
# Let tail flush any final bytes before we read.
sleep 0.2
kill "$TAIL_PID" 2>/dev/null || true
wait "$TAIL_PID" 2>/dev/null || true

if [ "$killed_early" -eq 1 ]; then
  echo "fc-test: microvm killed early; asserting markers" >&2
else
  echo "fc-test: microvm exited; asserting markers" >&2
fi

fail=0
for m in "${EXPECT[@]:-}"; do
  [ -z "$m" ] && continue
  if grep -qF -- "$m" "$LOG"; then
    echo "PASS expect: $m" >&2
  else
    echo "FAIL expect: $m (not found)" >&2
    fail=$((fail+1))
  fi
done
for m in "${UNEXPECT[@]:-}"; do
  [ -z "$m" ] && continue
  if grep -qF -- "$m" "$LOG"; then
    echo "FAIL unexpect: $m (found)" >&2
    fail=$((fail+1))
  else
    echo "PASS unexpect: $m (absent)" >&2
  fi
done

if [ $fail -gt 0 ]; then
  echo "fc-test: $fail assertion(s) failed" >&2
  exit 1
fi
echo "fc-test: all assertions passed" >&2
TAIL
} > "$OUT"
chmod +x "$OUT"
